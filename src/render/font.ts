export class UnknownGlyphError extends Error {}

/** Width in screen pixels, without the trailing gap after the last glyph. */
export function textWidth(text: string, size = 1): number {
  return text.length === 0 ? 0 : (text.length * ADVANCE - 1) * size;
}

export function drawText(plot: Plot, text: string, x: number, y: number, shade: Shade, size = 1): void {
  [...text.toUpperCase()].forEach((ch, i) => {
    const glyph = GLYPHS[ch];
    if (!glyph) throw new UnknownGlyphError(`no glyph for ${JSON.stringify(ch)}`);
    const left = x + i * ADVANCE * size;
    glyph.forEach((row, gy) => {
      for (let gx = 0; gx < row.length; gx++) {
        if (row[gx] === '#') plot(left + gx * size, y + gy * size, size, size, shade);
      }
    });
  });
}
